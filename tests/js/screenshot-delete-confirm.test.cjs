const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');

test('screenshot deletion requires confirmation; cancelling preserves images and review state',()=>{
 const node=()=>({children:[],append(...children){this.children.push(...children)},setAttribute(name,value){(this.attributes||={})[name]=value},removeAttribute(){},classList:{remove(){}},set innerHTML(value){this.children=[]}});
 const elements={'pc-screenshot-list':node(),'pc-screenshot-hint':node(),'pc-reviewed':{...node(),checked:true},'pc-submit':{disabled:false},'pc-review-confirmation':node(),'pc-review-hint':node()};
 let accept=false;
 const messages=[];
 const screenshots=[{preview:'first'},{preview:'second'},{preview:'third'}];
 const context=vm.createContext({screenshots,window:{},meta:{},sending:false,batchEntries:null,$:id=>elements[id],document:{createElement:node},confirm:message=>{messages.push(message);return accept}});
 const source=fs.readFileSync(require.resolve('../../api_test_tool/static/pingcode.js'),'utf8');
 vm.runInContext(source.slice(source.indexOf('function updateSubmitState()'),source.indexOf('function readScreenshot(')),context);
 context.renderScreenshots();
 const preview=elements['pc-screenshot-list'].children[1].children[0];
 assert.equal(preview.className,'report-image-preview');
 assert.equal(preview.attributes['data-image-src'],'second');
 assert.match(preview.attributes['aria-label'],/放大预览/);
 assert.equal(preview.children[0].src,'second');
 const remove=()=>elements['pc-screenshot-list'].children[1].children[1].onclick();
 remove();
 assert.match(messages[0],/确定删除第 2 张截图/);
 assert.deepEqual(screenshots.map(s=>s.preview),['first','second','third']);
 assert.equal(elements['pc-screenshot-list'].children.length,3);
 assert.equal(elements['pc-reviewed'].checked,true);
 assert.equal(elements['pc-submit'].disabled,false);
 accept=true;
 remove();
 assert.deepEqual(screenshots.map(s=>s.preview),['first','third']);
 assert.equal(elements['pc-screenshot-list'].children.length,2);
 assert.equal(elements['pc-reviewed'].checked,false);
 assert.equal(elements['pc-submit'].disabled,false);
 assert.match(elements['pc-screenshot-hint'].textContent,/2 张截图/);
 accept=false;
 remove();
 assert.match(messages[2],/第 2 张截图/);
 assert.deepEqual(screenshots.map(s=>s.preview),['first','third']);
});
